/** Get translations for any requested language code, falling back to English if missing */
export function getTranslations(lang: WorldLanguageCode): TranslationDictionary {
  if (DICTIONARIES[lang]) {
    return DICTIONARIES[lang];
  }
  // If not explicitly fully translated, synthesize with key terms and English base
  const base = DICTIONARIES.en;
  const langDef = WORLD_LANGUAGES.find((l) => l.code === lang);
  if (!langDef) return base;

  return {
    ...base,
    appTitle: `CARDIO-INTELLIGENCE [${langDef.nativeName}] Pulse-911 Studio`,
    subTitle: `3D Centralized Cardiovascular Orchestrator [${langDef.name}]`,
    patientGuidanceCalm: `(${langDef.nativeName}) Stay calm. Emergency medical help is arriving now.`,
  };
}
